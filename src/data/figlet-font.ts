/** render text into 5 rows of block art; unknown chars are dropped */
export function figletRender(text: string): string[] {
  const glyphs = [...text.toUpperCase()].map((c) => FIGLET_FONT[c]).filter(Boolean) as string[][]
  if (glyphs.length === 0) return []
  const rows: string[] = []
  for (let r = 0; r < FIGLET_ROWS; r++) rows.push(glyphs.map((g) => g[r]).join(' '))
  return rows
}
